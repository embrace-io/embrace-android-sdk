internal class StateRecorderTest {

    private lateinit var clock: FakeClock
    private lateinit var telemetryService: FakeInternalTelemetryService
    private lateinit var journal: RecordingJournal
    private lateinit var replay: RecordingReplay
    private lateinit var recorder: StateRecorder

    @Before
    fun setUp() {
        clock = FakeClock(START_MS)
        telemetryService = FakeInternalTelemetryService()
        journal = RecordingJournal()
        replay = RecordingReplay()
        recorder = newRecorder()
    }

    @Test
    fun `nothing is known before the first change`() {
        val snapshot = recorder.current()
        assertSame(StateSnapshot.EMPTY, snapshot)
        assertEquals(0L, snapshot.seq)
        assertEquals(0, snapshot.size)
        assertEquals("", snapshot.packed())
    }

    @Test
    fun `a state's first value is a change and takes a number`() {
        assertTrue(recorder.declare(StateDefinition("network"), "unknown", false, clock.now()))
        assertTrue(recorder.declare(StateDefinition("screen-automatic"), "Initializing", true, clock.now()))

        val snapshot = recorder.current()
        assertEquals(2L, snapshot.seq)
        assertEquals(listOf("network", "screen-automatic"), snapshot.names())
        assertEquals("unknown", snapshot.value(0))
        assertFalse(snapshot.isSystem(0))
        assertEquals("Initializing", snapshot.value(1))
        assertTrue(snapshot.isSystem(1))
        assertEquals("network=unknown;screen-automatic~Initializing", snapshot.packed())
    }

    @Test
    fun `a name that cannot name a state or is already declared is refused`() {
        assertFalse(recorder.declare(StateDefinition("Network"), "wifi", false, clock.now()))
        assertFalse(recorder.declare(StateDefinition("net work"), "wifi", false, clock.now()))
        assertFalse(recorder.declare(StateDefinition(""), "wifi", false, clock.now()))
        assertTrue(recorder.declare(StateDefinition("network"), "wifi", false, clock.now()))
        assertFalse(recorder.declare(StateDefinition("network", changeLimit = 5), "none", false, clock.now()))

        assertEquals(1L, recorder.current().seq)
        assertEquals("wifi", recorder.current().value(0))
    }

    @Test
    fun `an update for a state no data source declared is discarded`() {
        recorder.openPart(PART, clock.now())
        assertFalse(recorder.update("made-up", "value", false, clock.now()))

        assertSame(StateSnapshot.EMPTY, recorder.current())
        assertTrue(journal.changes().isEmpty())
        assertTrue(replay.changes.isEmpty())
    }

    @Test
    fun `an update that repeats the value is not a change`() {
        recorder.declare(StateDefinition("network"), "wifi", false, clock.now())
        recorder.openPart(PART, clock.now())

        assertFalse(recorder.update("network", "wifi", false, clock.now()))
        assertEquals(1L, recorder.current().seq)

        // the same text is a different value when one was generated by the SDK and the other was not
        assertTrue(recorder.update("network", "wifi", true, clock.now()))
        assertEquals(2L, recorder.current().seq)
        assertEquals(1, journal.changes().size)
    }

    @Test
    fun `every change of any state takes the next number and replaces one set of values`() {
        recorder.declare(StateDefinition("network"), "wifi", false, clock.now())
        recorder.declare(StateDefinition("power"), "unknown", false, clock.now())
        val before = recorder.current()

        recorder.update("power", "low", false, clock.now())
        val after = recorder.current()

        assertEquals(2L, before.seq)
        assertEquals("unknown", before.value(1))
        assertEquals(3L, after.seq)
        assertEquals("wifi", after.value(0))
        assertEquals("low", after.value(1))
        assertEquals("network=wifi;power=low", after.packed())
    }

    @Test
    fun `a value is cut at the limit before it is compared`() {
        val long = "a".repeat(StateRecorder.MAX_VALUE_LENGTH + 10)
        recorder.declare(StateDefinition("screen-automatic"), long, false, clock.now())

        val stored = recorder.current().value(0)
        assertEquals(StateRecorder.MAX_VALUE_LENGTH, stored.length)
        assertTrue(stored.endsWith("..."))

        // two values that differ only past the limit are one value
        assertFalse(recorder.update("screen-automatic", long + "b", false, clock.now()))
        assertEquals(1L, recorder.current().seq)
    }

    @Test
    fun `a change in a session part is listed with its number, its reporter's time and the value before`() {
        recorder.declare(StateDefinition("network"), "wifi", false, clock.now())
        recorder.openPart(PART, clock.now())
        val reportedAt = clock.now() - 500
        clock.tick(20)

        recorder.update("network", "none", false, reportedAt)

        val change = journal.changes().single()
        assertEquals(2L, change.seq)
        assertEquals("network", change.definition.name)
        assertEquals(reportedAt, change.timeMs)
        assertEquals("none", change.value)
        assertEquals("wifi", change.previousValue)
        assertEquals(2L, change.after.seq)
        assertSame(change, replay.changes.single())
        assertEquals(clock.now(), recorder.current().recordedAtMs)
    }

    @Test
    fun `a session part's journal opens with every state's value and the number they are as of`() {
        recorder.declare(StateDefinition("network"), "wifi", false, clock.now())
        recorder.declare(StateDefinition("screen-automatic"), "Initializing", true, clock.now())
        recorder.openPart(PART, clock.now())

        val opened = journal.records.single() as StateJournalRecord.PartOpened
        assertEquals(PART, opened.sessionPartId)
        assertEquals(2L, opened.initialSeq)
        assertEquals(listOf("network", "screen-automatic"), opened.states.map { it.name })
        assertEquals(listOf("wifi", "Initializing"), opened.states.map { it.value })
        assertEquals(listOf(false, true), opened.states.map { it.system })
        assertEquals(2L, replay.opened.single().first.seq)
    }

    @Test
    fun `a change made with no session part takes its number, replaces the value and is counted for its state`() {
        recorder.declare(StateDefinition("network"), "wifi", false, clock.now())
        recorder.declare(StateDefinition("power"), "normal", false, clock.now())
        recorder.openPart(PART, clock.now())
        recorder.closePart()
        journal.records.clear()

        repeat(250) { recorder.update("network", if (it % 2 == 0) "none" else "wifi", false, clock.now()) }

        assertEquals(252L, recorder.current().seq)
        assertEquals("wifi", recorder.current().value(0))
        assertTrue(journal.records.isEmpty())
        assertTrue(replay.changes.isEmpty())

        recorder.openPart(NEXT_PART, clock.now())
        val opened = journal.records.single() as StateJournalRecord.PartOpened
        assertEquals(252L, opened.initialSeq)
        assertEquals(250, opened.states[0].notInSessionCount)
        assertEquals(0, opened.states[1].notInSessionCount)

        // the count belongs to the stretch before that part only
        recorder.closePart()
        recorder.openPart("part-3", clock.now())
        assertEquals(0, (journal.records.last() as StateJournalRecord.PartOpened).states[0].notInSessionCount)
    }

    @Test
    fun `a state's first value given with no session part counts as a change made with none`() {
        recorder.declare(StateDefinition("network"), "wifi", false, clock.now())
        recorder.openPart(PART, clock.now())

        val opened = journal.records.single() as StateJournalRecord.PartOpened
        assertEquals(1, opened.states.single().notInSessionCount)
    }

    @Test
    fun `past a state's limit its changes are counted and not listed, and its value stays right`() {
        recorder.declare(StateDefinition("network", changeLimit = 3), "wifi", false, clock.now())
        recorder.declare(StateDefinition("power"), "normal", false, clock.now())
        recorder.openPart(PART, clock.now())

        repeat(5) { recorder.update("network", "value-$it", false, clock.now()) }
        recorder.update("power", "low", false, clock.now())
        recorder.update("network", "settled", true, clock.now())
        recorder.closePart()

        // numbers 3 to 5 are listed for the network, 6 and 7 refused, 8 is power's, 9 refused
        assertEquals(listOf(3L, 4L, 5L, 8L), journal.changes().map { it.seq })
        assertEquals(listOf(3L, 4L, 5L, 8L), replay.changes.map { it.seq })
        assertEquals("settled", recorder.current().value(0))
        assertEquals(9L, recorder.current().seq)

        val limit = journal.records.filterIsInstance<StateJournalRecord.LimitReached>().single()
        assertEquals("network", limit.state)
        assertEquals(3, limit.limit)
        // stated as soon as it is reached, so a journal with no end still has it
        assertTrue(journal.records.indexOf(limit) < journal.records.size - 1)

        val closed = journal.records.last() as StateJournalRecord.PartClosed
        assertEquals(3, closed.droppedChanges)
        val network = closed.states.single()
        assertEquals("network", network.name)
        assertEquals(3, network.droppedCount)
        assertEquals("settled", network.finalValue)
        assertTrue(network.finalSystem)
        assertEquals(9L, network.finalSeq)
        assertEquals(3, telemetryService.appliedLimits.count { it.first == "network_state_data_source" })
    }

    @Test
    fun `a state's first value counts toward its limit when it is given in a session part`() {
        recorder.openPart(PART, clock.now())
        recorder.declare(StateDefinition("network", changeLimit = 2), "wifi", false, clock.now())
        recorder.update("network", "none", false, clock.now())
        recorder.update("network", "wan", false, clock.now())

        assertEquals(listOf(1L, 2L), journal.changes().map { it.seq })
        assertNull(journal.changes().first().previousValue)
    }

    @Test
    fun `a state's limit starts again with each session part`() {
        recorder.declare(StateDefinition("network", changeLimit = 1), "wifi", false, clock.now())
        recorder.openPart(PART, clock.now())
        recorder.update("network", "none", false, clock.now())
        recorder.update("network", "wan", false, clock.now())
        recorder.closePart()
        recorder.openPart(NEXT_PART, clock.now())
        recorder.update("network", "wifi", false, clock.now())
        recorder.closePart()

        assertEquals(listOf(2L, 4L), journal.changes().map { it.seq })
        val closes = journal.records.filterIsInstance<StateJournalRecord.PartClosed>()
        assertEquals(listOf(1, 0), closes.map { it.droppedChanges })
        assertTrue(closes[1].states.isEmpty())
    }

    @Test
    fun `the limit across every state refuses changes and is stated once`() {
        recorder = newRecorder(globalChangeLimit = 4)
        recorder.declare(StateDefinition("network"), "wifi", false, clock.now())
        recorder.declare(StateDefinition("power"), "normal", false, clock.now())
        recorder.openPart(PART, clock.now())

        repeat(3) { recorder.update("network", "value-$it", false, clock.now()) }
        repeat(3) { recorder.update("power", "value-$it", false, clock.now()) }
        recorder.closePart()

        assertEquals(4, journal.changes().size)
        val limit = journal.records.filterIsInstance<StateJournalRecord.LimitReached>().single()
        assertNull(limit.state)
        assertEquals(4, limit.limit)
        val closed = journal.records.last() as StateJournalRecord.PartClosed
        assertEquals(2, closed.droppedChanges)
        assertEquals("power", closed.states.single().name)
        assertEquals("value-2", closed.states.single().finalValue)
    }

    @Test
    fun `changes an instrumentation reports it dropped are counted for the state only`() {
        recorder.declare(StateDefinition("network"), "wifi", false, clock.now())
        recorder.reportDropped("network", 2)
        recorder.reportDropped("made-up", 5)
        recorder.openPart(PART, clock.now())
        recorder.reportDropped("network", 1)
        recorder.closePart()

        assertEquals(1L, recorder.current().seq)
        val closed = journal.records.last() as StateJournalRecord.PartClosed
        assertEquals(0, closed.droppedChanges)
        val network = closed.states.single()
        assertEquals(3, network.droppedCount)
        assertNull(network.finalValue)
        assertEquals(0L, network.finalSeq)
    }

    @Test
    fun `a change keeps only the attributes its data source declared`() {
        val declared = setOf("frames.dropped", "frames.expected", "emb.app.state.new_value", "emb.state.sneaky")
        val definition = StateDefinition("screen-automatic", attributeKeys = declared)
        assertEquals(setOf("frames.dropped", "frames.expected"), definition.attributeKeys)

        recorder.declare(definition, "Home", false, clock.now())
        recorder.openPart(PART, clock.now())
        recorder.update(
            state = "screen-automatic",
            value = "Cart",
            system = false,
            timeMs = clock.now(),
            attributes = mapOf(
                "frames.dropped" to "3",
                "undeclared" to "x",
                "emb.app.state.new_value" to "Forged",
                "frames.expected" to "y".repeat(StateRecorder.MAX_VALUE_LENGTH + 1),
            ),
        )

        val attributes = journal.changes().single().attributes
        assertEquals(setOf("frames.dropped", "frames.expected"), attributes.keys)
        assertEquals("3", attributes["frames.dropped"])
        assertEquals(StateRecorder.MAX_VALUE_LENGTH, attributes.getValue("frames.expected").length)
    }

    @Test
    fun `a data source can declare at most seven attribute keys`() {
        val definition = StateDefinition("screen-automatic", attributeKeys = (1..10).map { "key-$it" }.toSet())
        assertEquals(StateDefinition.MAX_CHANGE_ATTRIBUTES, definition.attributeKeys.size)
    }

    @Test
    fun `a time is placed among the recent snapshots, and a tie counts as after the change`() {
        recorder.declare(StateDefinition("network"), "wifi", false, clock.now())
        val firstAt = clock.now()
        clock.tick(100)
        recorder.update("network", "none", false, clock.now())
        val secondAt = clock.now()
        clock.tick(100)
        recorder.update("network", "wan", false, clock.now())

        assertSame(StateSnapshot.EMPTY, recorder.snapshotAt(firstAt - 1))
        assertEquals(1L, recorder.snapshotAt(firstAt)?.seq)
        assertEquals(1L, recorder.snapshotAt(secondAt - 1)?.seq)
        assertEquals(2L, recorder.snapshotAt(secondAt)?.seq)
        assertEquals("none", recorder.snapshotAt(secondAt + 50)?.value(0))
        assertEquals(3L, recorder.snapshotAt(clock.now())?.seq)
        assertEquals(3L, recorder.snapshotAt(clock.now() + 10_000)?.seq)
    }

    @Test
    fun `a time older than the window has no snapshot`() {
        recorder = newRecorder(windowSize = 4)
        recorder.declare(StateDefinition("network"), "value-0", false, clock.now())
        val firstAt = clock.now()
        repeat(6) {
            clock.tick(10)
            recorder.update("network", "value-${it + 1}", false, clock.now())
        }

        // changes 4 to 7 are in the window, recorded at 30ms to 60ms after the first
        assertNull(recorder.snapshotAt(firstAt))
        assertNull(recorder.snapshotAt(firstAt + 29))
        assertEquals(4L, recorder.snapshotAt(firstAt + 30)?.seq)
        assertEquals(6L, recorder.snapshotAt(firstAt + 59)?.seq)
        assertEquals(7L, recorder.snapshotAt(firstAt + 60)?.seq)
    }

    @Test
    fun `a session part that starts before the last one ended closes it first`() {
        recorder.declare(StateDefinition("network"), "wifi", false, clock.now())
        recorder.openPart(PART, clock.now())
        recorder.openPart(NEXT_PART, clock.now())

        assertEquals(
            listOf(PART, PART, NEXT_PART),
            journal.records.map { it.sessionPartId },
        )
        assertTrue(journal.records[1] is StateJournalRecord.PartClosed)
    }

    @Test
    fun `data sources reach the recorder over the event bus`() {
        val eventBus = EventBus(FakeErrorHandler())
        recorder.attach(eventBus)
        recorder.openPart(PART, clock.now())

        eventBus.emit(StateEvents.DECLARED, StateDeclaration(StateDefinition("network"), "wifi", false, clock.now()))
        eventBus.emit(StateEvents.UPDATED, StateUpdate("network", "none", false, clock.now()))
        eventBus.emit(StateEvents.UPDATED, StateUpdate("made-up", "none", false, clock.now()))
        eventBus.emit(StateEvents.DROPPED, StateDrops("network", 4))
        recorder.closePart()

        assertEquals("network=none", recorder.current().packed())
        assertEquals(2L, recorder.current().seq)
        assertEquals(4, (journal.records.last() as StateJournalRecord.PartClosed).states.single().droppedCount)
    }

    @Test
    fun `changes reported from several threads take one order, and every snapshot agrees with the history`() {
        recorder = newRecorder(globalChangeLimit = Int.MAX_VALUE)
        val states = (0 until STATES).map { "state-$it" }
        states.forEach { recorder.declare(StateDefinition(it, changeLimit = Int.MAX_VALUE), "initial", false, clock.now()) }
        recorder.openPart(PART, clock.now())

        val executor = Executors.newFixedThreadPool(STATES + READERS)
        val start = CountDownLatch(1)
        val observed = ConcurrentLinkedQueue<StateSnapshot>()
        val writers = states.map { state ->
            executor.submit {
                start.await()
                repeat(CHANGES_PER_STATE) { recorder.update(state, "$state-$it", false, clock.now()) }
            }
        }
        val readers = (0 until READERS).map {
            executor.submit {
                start.await()
                repeat(CHANGES_PER_STATE) { observed.add(recorder.current()) }
            }
        }
        start.countDown()
        (writers + readers).forEach { it.get(30, TimeUnit.SECONDS) }
        executor.shutdown()

        // every change took exactly one number, and the journal has them in the order of the sequence
        val changes = journal.changes()
        val expectedLast = (STATES + STATES * CHANGES_PER_STATE).toLong()
        assertEquals(STATES * CHANGES_PER_STATE, changes.size)
        assertTrue(changes.withIndex().all { (index, change) -> change.seq == STATES + 1L + index })
        assertEquals(expectedLast, recorder.current().seq)

        // replaying the journal up to a snapshot's number gives that snapshot's values, whichever thread read it
        val history = HashMap<Long, Map<String, String>>()
        val values = states.associateWithTo(LinkedHashMap()) { "initial" }
        history[STATES.toLong()] = values.toMap()
        changes.forEach {
            values[it.definition.name] = it.value
            history[it.seq] = values.toMap()
        }
        assertTrue(observed.isNotEmpty())
        observed.forEach { snapshot ->
            val expected = history.getValue(snapshot.seq)
            assertTrue(expected == snapshot.names().associateWith { snapshot.value(snapshot.indexOf(it)) })
        }
    }

    private fun newRecorder(
        globalChangeLimit: Int = StateRecorder.GLOBAL_CHANGE_LIMIT,
        windowSize: Int = StateRecorder.WINDOW_SIZE,
    ) = StateRecorder(clock, telemetryService, globalChangeLimit, windowSize).also {
        it.journal = journal
        it.replay = replay
    }

    private fun StateSnapshot.names(): List<String> = (0 until size).map(::name)

    private class RecordingJournal : StateJournal {
        val records = ArrayList<StateJournalRecord>()

        override fun append(record: StateJournalRecord) {
            records.add(record)
        }

        fun changes(): List<StateChange> = records.filterIsInstance<StateJournalRecord.Change>().map { it.change }
    }

    private class RecordingReplay : StateReplay {
        val opened = ArrayList<Pair<StateSnapshot, Long>>()
        val changes = ArrayList<StateChange>()

        override fun onPartOpened(snapshot: StateSnapshot, timeMs: Long) {
            opened.add(snapshot to timeMs)
        }

        override fun onChange(change: StateChange) {
            changes.add(change)
        }
    }

    private companion object {
        const val START_MS = 1_700_000_000_000L
        const val PART = "part-1"
        const val NEXT_PART = "part-2"
        const val STATES = 6
        const val READERS = 4
        const val CHANGES_PER_STATE = 2_000
    }
}
