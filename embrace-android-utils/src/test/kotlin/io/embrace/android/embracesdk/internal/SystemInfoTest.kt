package io.embrace.android.embracesdk.internal

import android.os.Build
import android.os.Build.VERSION_CODES.LOLLIPOP
import android.os.Build.VERSION_CODES.LOLLIPOP_MR1
import android.os.Build.VERSION_CODES.M
import android.os.Build.VERSION_CODES.TIRAMISU
import androidx.test.ext.junit.runners.AndroidJUnit4
import io.embrace.android.embracesdk.internal.utils.VersionChecker
import org.junit.Assert.assertEquals
import org.junit.Assert.assertSame
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.shadows.ShadowBuild

@RunWith(AndroidJUnit4::class)
internal class SystemInfoTest {

    @Test
    fun `verify default system info`() {
        // Not all attributes are verified given some are just stubs generated by the testing framework
        ShadowBuild.setVersionRelease("13")
        with(SystemInfo()) {
            assertEquals("android", osName)
            assertEquals("linux", osType)
            assertEquals(Build.VERSION.SDK_INT.toString(), androidOsApiLevel)
            assertEquals("13", osVersion)
            assertSame(Build.VERSION.BASE_OS, osBuild)
        }
    }

    @Test
    fun `os build is only read from API 23`() {
        forEachSdk(LOLLIPOP, LOLLIPOP_MR1) { versionChecker ->
            assertEquals("", getOsBuild(versionChecker))
        }
        forEachSdk(M, TIRAMISU) { versionChecker ->
            assertSame(Build.VERSION.BASE_OS, getOsBuild(versionChecker))
        }
    }

    @Test
    fun `primary ABI is the first supported ABI listed in the BUILD object`() {
        ShadowBuild.setSupportedAbis(arrayOf("arm64-v8a", "armeabi-v7a"))
        assertEquals("arm64-v8a", SystemInfo().primaryAbi)

        ShadowBuild.setSupportedAbis(arrayOf("x86_64", "x86"))
        assertEquals("x86_64", SystemInfo().primaryAbi)

        ShadowBuild.setSupportedAbis(emptyArray())
        assertEquals(Build.UNKNOWN, SystemInfo().primaryAbi)

        // Takes the first regardless if subsequent ones are supported
        ShadowBuild.setSupportedAbis(arrayOf("riscv64", "arm64-v8a"))
        assertEquals(Build.UNKNOWN, SystemInfo().primaryAbi)
    }

    private fun forEachSdk(vararg sdkInts: Int, action: (VersionChecker) -> Unit) {
        sdkInts.forEach { sdkInt ->
            try {
                action(VersionChecker { min -> sdkInt >= min })
            } catch (e: AssertionError) {
                throw AssertionError("Failed at API $sdkInt", e)
            }
        }
    }
}
