package io.embrace.android.embracesdk.testcases.features

import android.content.Context
import androidx.test.core.app.ApplicationProvider
import io.embrace.android.embracesdk.assertions.waitUntilConditionMet
import io.embrace.android.embracesdk.internal.config.PersistedConfig
import io.embrace.android.embracesdk.internal.config.cache.CachedConfiguration
import io.embrace.android.embracesdk.internal.config.remote.RemoteConfig
import io.embrace.android.embracesdk.internal.serialization.EmbraceBinary
import io.embrace.android.embracesdk.testframework.OtelSdkMode
import io.embrace.android.embracesdk.testframework.SdkIntegrationTestRule
import io.embrace.android.embracesdk.testframework.actions.EmbracePayloadAssertionInterface
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.ParameterizedRobolectricTestRunner
import java.io.File

/**
 * Tests how the SDK behaves when controlling by 'remote config'. This is a HTTP response from the
 * Embrace server that can enable or disable individual features or the entire SDK.
 */
@RunWith(ParameterizedRobolectricTestRunner::class)
internal class RemoteConfigTest(
    private val otelSdkMode: OtelSdkMode,
) {

    private val sdkDisabledConfig = RemoteConfig(0)
    private val sdkEnabledConfig = RemoteConfig(100)

    @Rule
    @JvmField
    val testRule: SdkIntegrationTestRule = SdkIntegrationTestRule(otelSdkMode = otelSdkMode)

    @Test
    fun `SDK can start`() {
        testRule.runTest(
            persistedRemoteConfig = sdkEnabledConfig,
            serverResponseConfig = sdkDisabledConfig,
            preSdkStartAction = {
                assertNoConfigPersisted()
                assertFalse(embrace.isStarted)
            },
            testCaseAction = {
                assertTrue(embrace.isStarted)
            },
            assertAction = {
                assertConfigStored(0)
            })
    }

    @Test
    fun `SDK disabled via config cannot start`() {
        testRule.runTest(
            persistedRemoteConfig = sdkDisabledConfig,
            serverResponseConfig = sdkEnabledConfig,
            expectSdkToStart = false,
            preSdkStartAction = {
                assertNoConfigPersisted()
            },
            testCaseAction = {
                assertFalse(embrace.isStarted)
            },
            assertAction = {
                assertConfigRequested(1)
                assertConfigStored(100)
            })
    }

    @Test
    fun `a malformed config response leaves the persisted config intact`() {
        testRule.runTest(
            persistedRemoteConfig = sdkEnabledConfig,
            serverResponseConfigJson = """{"threshold":"not-a-number"}""",
            testCaseAction = {
                assertTrue(embrace.isStarted)
            },
            assertAction = {
                assertConfigRequested(1)

                // good config already on disk is not overwritten
                val persisted = readPersistedConfigResponse()
                assertEquals(100, persisted.cfg?.threshold)
                assertEquals("persisted_etag", persisted.etag)
            })
    }

    @Test
    fun `a stale binary config cache is regenerated by the next config request`() {
        // launch with an unreadable binary config cache from previous version
        testRule.runTest(
            persistedRemoteConfig = sdkEnabledConfig,
            serverResponseConfigEtag = "persisted_etag",
            setupAction = {
                writeStaleBinaryConfigCache()
            },
            testCaseAction = {
                assertTrue(embrace.isStarted)
            },
            assertAction = {
                assertConfigRequested(1)

                // no e-tag is used - we attempt to regenerate the config for next launch
                assertEquals(listOf<String?>(null), getConfigRequestEtags())
                waitUntilConditionMet(
                    condition = { it != null },
                    dataProvider = ::readBinaryConfigCache,
                )
            }
        )

        testRule.services.networkConnectivityService.close()
        testRule.services.otelSdkConfig.close()
        testRule.services.workerThreadPool.close()

        // the next launch should load the regenerated binary cache and use e-tags again
        testRule.runTest(
            persistedRemoteConfig = sdkEnabledConfig,
            serverResponseConfigEtag = "persisted_etag",
            preSdkStartAction = {
                val cached = checkNotNull(readBinaryConfigCache()) {
                    "Binary config cache was not regenerated."
                }
                assertEquals(100, cached.remoteConfig.threshold)
                assertEquals("persisted_etag", cached.etag)
            },
            testCaseAction = {
                assertTrue(embrace.isStarted)
            },
            assertAction = {
                assertConfigRequested(1)
                assertEquals(listOf("persisted_etag"), getConfigRequestEtags())
            }
        )
    }

    private fun configStorageDir(): File {
        val ctx = ApplicationProvider.getApplicationContext<Context>()
        return File(ctx.filesDir, PersistedConfig.STORAGE_DIR_NAME)
    }

    private fun writeStaleBinaryConfigCache() {
        val storageDir = configStorageDir().apply { mkdirs() }
        File(storageDir, PersistedConfig.CACHED_CONFIG_FILE_NAME).writeBytes(ByteArray(8))
    }

    private fun readBinaryConfigCache(): CachedConfiguration? = runCatching {
        File(configStorageDir(), PersistedConfig.CACHED_CONFIG_FILE_NAME).inputStream().buffered().use {
            EmbraceBinary.decodeFromStream(CachedConfiguration.serializer(), it)
        }
    }.getOrNull()

    private fun EmbracePayloadAssertionInterface.assertConfigStored(
        expectedThreshold: Int,
    ) {
        assertConfigRequested(1)
        waitUntilConditionMet(
            condition = { response ->
                response != null && expectedThreshold == response.cfg?.threshold && "server_etag_value" == response.etag
            },
            dataProvider = {
                runCatching {
                    readPersistedConfigResponse()
                }.getOrNull()
            }
        )
    }

    internal companion object {
        @JvmStatic
        @ParameterizedRobolectricTestRunner.Parameters(name = "{0}")
        fun modes(): List<Array<Any>> = OtelSdkMode.parameters()
    }
}
